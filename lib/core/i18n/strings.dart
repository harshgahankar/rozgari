String tr(String lang, String key) =>
    kStrings[lang]?[key] ?? kStrings['en']![key] ?? key;

/// `trArgs('hi', 'hello', {'name': 'Ramesh'})` → नमस्ते, Ramesh 🙏
String trArgs(String lang, String key, Map<String, String> args) {
  var s = tr(lang, key);
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

